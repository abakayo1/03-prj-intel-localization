function translatePage(language) {
  const translations = language === "ar" ? arabicText : additionalTranslations[language] || {};
  const altTranslations = language === "ar" ? arabicAltText : additionalAltTranslations[language] || {};

  document.querySelectorAll("h1, h2, h3:not(.accordion-header), p, strong, span, a, button, label, .accordion-body").forEach((element) => {
    if (!originalText.has(element)) {
      originalText.set(element, element.textContent);
    }

    const englishText = originalText.get(element);
    const lookupText = englishText.trim().replace(/\s+/g, " ");
    element.textContent = translations[lookupText] || englishText;
  });

  document.querySelectorAll("img[alt]").forEach((image) => {
    if (!originalAltText.has(image)) {
      originalAltText.set(image, image.alt);
    }

    const englishAlt = originalAltText.get(image);
    image.alt = altTranslations[englishAlt] || englishAlt;
  });

  document.querySelectorAll("[aria-label]").forEach((element) => {
    if (!originalLabels.has(element)) {
      originalLabels.set(element, element.getAttribute("aria-label"));
    }

    const englishLabel = originalLabels.get(element);
    element.setAttribute("aria-label", translations[englishLabel] || englishLabel);
  });

  document.title = translations["Sustainability Through the Ages"] || "Intel Sustainability Through the Ages";
  languagePicker.value = language;

  if (newsletterSubmitted) {
    newsletterStatus.textContent = language === "ar"
      ? "لم يتم إرسال بريدك الإلكتروني؛ فهذه الصفحة غير متصلة بخدمة النشرة البريدية من Intel بعد."
      : additionalNewsletterMessages[language]
        || "This page is not connected to Intel's newsletter service yet. Your email was not sent.";
  }
}

function getLanguageDirection(languageTag) {
  try {
    const locale = new Intl.Locale(languageTag);
    if (typeof locale.getTextInfo === "function") {
      return locale.getTextInfo().direction;
    }

    const likelyScript = locale.maximize().script;
    if (likelyScript) {
      return rtlScripts.has(likelyScript) ? "rtl" : "ltr";
    }
  } catch {
    // Fall back to the language or script tag when locale APIs reject the value.
  }

  const parts = languageTag.split(/[-_]/);
  const explicitScript = parts.find((part) => /^[a-z]{4}$/i.test(part));
  if (explicitScript) {
    const script = explicitScript[0].toUpperCase() + explicitScript.slice(1).toLowerCase();
    return rtlScripts.has(script) ? "rtl" : "ltr";
  }

  return rtlLanguages.has((parts[0] || "").toLowerCase()) ? "rtl" : "ltr";
}

function updateTextDirection() {
  const translatedRtl = page.classList.contains("translated-rtl");
  const translatedLtr = page.classList.contains("translated-ltr");
  const language = (page.lang || "en").toLowerCase();
  const baseLanguage = language.split("-")[0];
  const direction = translatedRtl
    ? "rtl"
    : translatedLtr
      ? "ltr"
      : getLanguageDirection(language);

  page.dir = direction;
  bootstrapStylesheet.href = direction === "rtl" ? bootstrapRtl : bootstrapLtr;

  // Google Translate supplies its own words; the local dictionary handles English and Arabic selections.
  if (!translatedRtl && !translatedLtr && (baseLanguage === "en" || baseLanguage === "ar" || additionalTranslations[baseLanguage])) {
    translatePage(baseLanguage);
  }
}

languagePicker.addEventListener("change", () => {
  page.classList.remove("translated-ltr", "translated-rtl");
  page.lang = languagePicker.value;
  updateTextDirection();
});

new MutationObserver(updateTextDirection).observe(page, {
  attributes: true,
  attributeFilter: ["class", "lang"],
});
updateTextDirection();

newsletterForm.addEventListener("submit", (event) => {
  event.preventDefault();
  newsletterSubmitted = true;
  translatePage(page.lang.toLowerCase().startsWith("ar") ? "ar" : "en");
});
